def decode_name(data: bytes, terminator: int = NAME_TERMINATOR) -> str:
    """Decode a fixed-size name slot; stops at the terminator.

    Unknown bytes render as ``?[XX]`` so corrupt data stays visible.
    """
    out = []
    for b in data:
        if b == terminator:
            break
        out.append(CHARMAP.get(b, f"?[{b:02X}]"))
    return "".join(out)
